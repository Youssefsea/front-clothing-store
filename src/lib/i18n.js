export const translations = { en, ar };

export function getLangDir(lang) {
  return (LANGS[lang] || LANGS[DEFAULT_LANG]).dir;
}

export function translate(lang, key, vars) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  let out = dict[key] != null ? dict[key] : en[key] != null ? en[key] : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      out = out.replace(`{${k}}`, String(v));
    }
  }
  return out;
}

// Maps a backend order status value to its translation key.
export function statusLabelKey(status) {
  return {
    pending: "status.pending",
    paid: "status.paid",
    shipped: "status.shipped",
    delivered: "status.delivered",
    cancelled: "status.cancelled",
  }[status] || "status.unavailable";
}